//! Generates `~/.config/hypr/ymux.lua` from the config (spec 2, 3 item 2, 3.2.1;
//! facts from docs/spikes.md S2/S3).

use crate::config::Config;
use std::fmt::Write;

/// Escapes a value for use inside a double-quoted Lua string.
pub fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// `SUPER+SHIFT+B` -> `SUPER + SHIFT + B` (escaped for Lua).
fn spaced(keys: &str) -> String {
    esc(&keys.split('+').map(str::trim).collect::<Vec<_>>().join(" + "))
}

/// Leader action key as Hyprland spells it (plain, no modifier except SHIFT for symbols).
fn leader_key(key: &str) -> String {
    match key {
        // physical keycodes: with Shift held the keysym is `dollar` / `colon`
        "$" => "SHIFT + code:13".into(),
        ":" => "SHIFT + code:47".into(),
        "," => "comma".into(),
        "." => "period".into(),
        "/" => "slash".into(),
        ";" => "semicolon".into(),
        "'" => "apostrophe".into(),
        "-" => "minus".into(),
        "=" => "equal".into(),
        "[" => "bracketleft".into(),
        "]" => "bracketright".into(),
        "\\" => "backslash".into(),
        "`" => "grave".into(),
        k if k.chars().count() == 1 => k.to_uppercase(),
        k => esc(k),
    }
}

pub fn generate(cfg: &Config, exe: &str) -> String {
    let exe = &esc(exe);
    let step = cfg.resize_step;
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "-- Generated by ymux from ~/.ymux.conf. Do not edit this file;").unwrap();
    writeln!(w, "-- edit ~/.ymux.conf instead and ymux regenerates it.").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "-- Omarchy's per-monitor workspace renumbering is replaced by ymux (spec 3.2.1).").unwrap();
    writeln!(w, "o.workspaces.reconcile = function() end").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "local ymux_exe = \"{exe}\"").unwrap();
    writeln!(w, "local ymux_timer = nil").unwrap();
    writeln!(w, "local function ymux_stop_timer()").unwrap();
    writeln!(w, "  if ymux_timer then ymux_timer:set_enabled(false) ymux_timer = nil end").unwrap();
    writeln!(w, "end").unwrap();
    writeln!(w, "local function ymux_reset()").unwrap();
    writeln!(w, "  ymux_stop_timer()").unwrap();
    writeln!(w, "  hl.dispatch(hl.dsp.submap(\"reset\"))").unwrap();
    writeln!(w, "end").unwrap();
    writeln!(w, "local function ymux_run(args)").unwrap();
    writeln!(w, "  hl.dispatch(hl.dsp.exec_cmd(ymux_exe .. \" \" .. args))").unwrap();
    writeln!(w, "end").unwrap();
    writeln!(w).unwrap();
    // resize mode (spec 2 leader details 6): Super held + arrows; leaving when Super
    // is released, polled like the user's mouse mode (bindings.lua)
    writeln!(w, "local ymux_resize_timer = nil").unwrap();
    writeln!(w, "local function ymux_resize_exit()").unwrap();
    writeln!(w, "  if ymux_resize_timer then ymux_resize_timer:set_enabled(false) end").unwrap();
    writeln!(w, "  hl.dispatch(hl.dsp.submap(\"reset\"))").unwrap();
    writeln!(w, "end").unwrap();
    writeln!(w, "ymux_resize_timer = hl.timer(function()").unwrap();
    writeln!(w, "  if not hl.is_key_down(\"Super_L\") and not hl.is_key_down(\"Super_R\") then ymux_resize_exit() end").unwrap();
    writeln!(w, "end, {{ timeout = 50, type = \"repeat\" }})").unwrap();
    writeln!(w, "ymux_resize_timer:set_enabled(false)").unwrap();
    writeln!(w, "local function ymux_resize_enter()").unwrap();
    writeln!(w, "  ymux_stop_timer()").unwrap();
    writeln!(w, "  ymux_resize_timer:set_enabled(true)").unwrap();
    writeln!(w, "  hl.dispatch(hl.dsp.submap(\"ymux_resize\"))").unwrap();
    writeln!(w, "end").unwrap();
    writeln!(w).unwrap();
    let arrows = [("LEFT", -(step as i64), 0i64), ("RIGHT", step as i64, 0), ("UP", 0, -(step as i64)), ("DOWN", 0, step as i64)];
    writeln!(w, "hl.define_submap(\"ymux_resize\", function()").unwrap();
    for (k, dx, dy) in arrows {
        writeln!(
            w,
            "  o.bind(\"SUPER + {k}\", \"ymux resize\", function() hl.dispatch(hl.dsp.window.resize({{ x = {dx}, y = {dy}, relative = true }})) end, {{ repeating = true }})"
        )
        .unwrap();
    }
    writeln!(w, "  for _, k in ipairs({{ \"Super_L\", \"Super_R\", \"SUPER + Super_L\", \"SUPER + Super_R\" }}) do").unwrap();
    writeln!(w, "    hl.bind(k, function() end, {{ description = \"ymux ignore modifier\" }})").unwrap();
    writeln!(w, "  end").unwrap();
    writeln!(w, "  o.bind(\"ESCAPE\", \"ymux leave resize\", ymux_resize_exit)").unwrap();
    writeln!(w, "  hl.bind(\"catchall\", ymux_resize_exit, {{ description = \"ymux leave resize\", release = true }})").unwrap();
    writeln!(w, "end)").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "hl.define_submap(\"ymux\", function()").unwrap();
    for (k, dx, dy) in arrows {
        writeln!(
            w,
            "  o.bind(\"SUPER + {k}\", \"ymux resize\", function() ymux_resize_enter() hl.dispatch(hl.dsp.window.resize({{ x = {dx}, y = {dy}, relative = true }})) end, {{ repeating = true }})"
        )
        .unwrap();
    }
    for (key, action) in &cfg.binds {
        writeln!(
            w,
            "  o.bind(\"{}\", \"ymux {}\", function() ymux_reset() ymux_run(\"action {}\") end)",
            leader_key(key),
            action.name(),
            action.name()
        )
        .unwrap();
    }
    writeln!(w, "  for _, k in ipairs({{ \"Super_L\", \"Super_R\", \"SUPER + Super_L\", \"SUPER + Super_R\", \"Shift_L\", \"Shift_R\", \"SHIFT + Shift_L\", \"SHIFT + Shift_R\" }}) do").unwrap();
    writeln!(w, "    hl.bind(k, function() end, {{ description = \"ymux ignore modifier\" }})").unwrap();
    writeln!(w, "  end").unwrap();
    writeln!(w, "  o.bind(\"ESCAPE\", \"ymux leave leader\", ymux_reset)").unwrap();
    // on release: in Hyprland 0.56.2 a press catch-all fires on every key press, so a
    // Shift press would end leader mode before `$` / `:` (spikes.md, phase 3 acceptance)
    writeln!(w, "  hl.bind(\"catchall\", ymux_reset, {{ description = \"ymux leave leader\", release = true }})").unwrap();
    writeln!(w, "end)").unwrap();
    writeln!(w).unwrap();
    writeln!(w, "o.bind(\"{}\", \"ymux leader\", function()", spaced(&cfg.leader)).unwrap();
    writeln!(w, "  ymux_stop_timer()").unwrap();
    writeln!(w, "  hl.dispatch(hl.dsp.submap(\"ymux\"))").unwrap();
    writeln!(
        w,
        "  ymux_timer = hl.timer(ymux_reset, {{ timeout = {}, type = \"oneshot\" }})",
        cfg.leader_timeout_ms
    )
    .unwrap();
    writeln!(w, "end)").unwrap();
    writeln!(w).unwrap();
    for (keys, action) in &cfg.global_binds {
        writeln!(
            w,
            "o.bind(\"{}\", \"ymux {}\", \"{exe} action {}\")",
            spaced(keys),
            action.name(),
            action.name()
        )
        .unwrap();
    }
    writeln!(w).unwrap();
    writeln!(w, "-- Omarchy binds made session-local (spec 2).").unwrap();
    for n in 1..=10u32 {
        let code = n + 9;
        writeln!(w, "o.rebind(\"SUPER + code:{code}\", \"ymux workspace {n}\", \"{exe} focus {n}\")").unwrap();
        writeln!(w, "o.rebind(\"SUPER + SHIFT + code:{code}\", \"ymux move window to workspace {n}\", \"{exe} move {n}\")").unwrap();
        writeln!(
            w,
            "o.rebind(\"SUPER + SHIFT + ALT + code:{code}\", \"ymux move window silently to workspace {n}\", \"{exe} move {n} --silent\")"
        )
        .unwrap();
    }
    let simple = [
        ("SUPER + TAB", "ymux next workspace", "next"),
        ("SUPER + SHIFT + TAB", "ymux previous workspace", "prev"),
        ("SUPER + CTRL + TAB", "ymux former workspace", "previous"),
        ("SUPER + mouse_down", "ymux next workspace", "next"),
        ("SUPER + mouse_up", "ymux previous workspace", "prev"),
        ("SUPER + SHIFT + ALT + LEFT", "ymux move session left", "session-move l"),
        ("SUPER + SHIFT + ALT + RIGHT", "ymux move session right", "session-move r"),
        ("SUPER + SHIFT + ALT + UP", "ymux move session up", "session-move u"),
        ("SUPER + SHIFT + ALT + DOWN", "ymux move session down", "session-move d"),
        // Alt + Tab skips placeholders (spec 2 takeover 8); one unbind removes both
        // Omarchy binds per key (spikes.md S2)
        ("ALT + TAB", "ymux next window", "cycle next"),
        ("ALT + SHIFT + TAB", "ymux previous window", "cycle prev"),
        // Omarchy's close (tiling.lua:1): closes like Leader + x (spec 2 takeover 9)
        ("SUPER + W", "ymux close window", "action kill-tile"),
    ];
    for (keys, desc, args) in simple {
        writeln!(w, "o.rebind(\"{keys}\", \"{desc}\", \"{exe} {args}\")").unwrap();
    }
    writeln!(w).unwrap();
    writeln!(w, "-- Placeholders: invisible, undecorated, opened on the hidden stash (spec 5.7).").unwrap();
    writeln!(
        w,
        "o.window(\"^ymux-placeholder$\", {{ workspace = \"special:ymux-stash silent\", border_size = 0, no_shadow = true, no_blur = true, decorate = false, no_dim = true, rounding = 0, no_anim = true }})"
    )
    .unwrap();
    writeln!(w).unwrap();
    writeln!(w, "-- Start the daemon; it exits at once if one is already running (spec 3 item 2).").unwrap();
    writeln!(w, "hl.exec_cmd(\"{exe} daemon\")").unwrap();
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{parse, Config};

    const EXE: &str = "/home/u/.local/bin/ymux";
    fn lua() -> String {
        generate(&Config::default(), EXE)
    }

    #[test]
    fn disables_reconcile_and_starts_daemon_last() {
        let g = lua();
        assert!(g.contains("o.workspaces.reconcile = function() end"));
        assert!(g.trim_end().ends_with("hl.exec_cmd(\"/home/u/.local/bin/ymux daemon\")"));
    }

    #[test]
    fn number_row_uses_omarchy_keycodes() {
        let g = lua();
        assert!(g.contains("o.rebind(\"SUPER + code:10\", \"ymux workspace 1\", \"/home/u/.local/bin/ymux focus 1\")"));
        assert!(g.contains("\"SUPER + SHIFT + ALT + code:19\""));
        assert!(g.contains("ymux move 10 --silent"));
        assert!(g.contains("o.rebind(\"SUPER + SHIFT + code:11\", \"ymux move window to workspace 2\", \"/home/u/.local/bin/ymux move 2\")"));
    }

    #[test]
    fn leader_actions_bound_plain_only() {
        let g = lua();
        assert!(g.contains("o.bind(\"C\", \"ymux new-workspace\""));
        assert!(!g.contains("o.bind(\"SUPER + C\""));
        // bound by physical keycode: with Shift held the keysym is `dollar` / `colon`,
        // so a keysym bind never matches (seen live at phase 3 acceptance)
        assert!(g.contains("o.bind(\"SHIFT + code:13\", \"ymux rename-session\""));
        assert!(g.contains("o.bind(\"SHIFT + code:47\", \"ymux command-prompt\""));
        assert!(g.contains("o.bind(\"comma\", \"ymux rename-workspace\""));
        assert!(g.contains("o.bind(\"period\", \"ymux move-workspace\""));
        assert!(g.contains("\"Super_L\""));
        // `$` and `:` need Shift: a Shift press must not end leader mode
        assert!(g.contains("\"Shift_L\"") && g.contains("\"SHIFT + Shift_R\""));
        // the catch-all fires on every press in Hyprland 0.56.2, so it must act on
        // release, or a Shift press ends leader mode before `$` / `:` (phase 3 acceptance)
        assert!(g.contains("hl.bind(\"catchall\", ymux_reset, { description = \"ymux leave leader\", release = true })"));
    }

    #[test]
    fn leader_and_submap_wiring() {
        let g = lua();
        assert!(g.contains("o.bind(\"SUPER + B\", \"ymux leader\""));
        assert!(g.contains("hl.define_submap(\"ymux\""));
        assert!(g.contains("type = \"oneshot\""));
    }

    #[test]
    fn custom_leader_is_used() {
        let (c, _) = parse("set leader SUPER+N\n");
        assert!(generate(&c, "x").contains("o.bind(\"SUPER + N\", \"ymux leader\""));
    }

    #[test]
    fn leader_timeout_from_config() {
        let (c, _) = parse("set leader-timeout 1500\n");
        assert!(generate(&c, "x").contains("timeout = 1500"));
    }

    #[test]
    fn global_binds_and_takeovers() {
        let g = lua();
        assert!(g.contains("o.bind(\"SHIFT + CTRL + ALT + H\", \"ymux previous-workspace\", \"/home/u/.local/bin/ymux action previous-workspace\")"));
        assert!(g.contains("o.rebind(\"SUPER + TAB\", \"ymux next workspace\", \"/home/u/.local/bin/ymux next\")"));
        assert!(g.contains("o.rebind(\"SUPER + CTRL + TAB\""));
        assert!(g.contains("o.rebind(\"SUPER + mouse_down\""));
        assert!(g.contains("o.rebind(\"SUPER + SHIFT + ALT + LEFT\", \"ymux move session left\", \"/home/u/.local/bin/ymux session-move l\")"));
    }

    #[test]
    fn alt_tab_taken_over_once_per_key() {
        let g = lua();
        assert_eq!(g.matches("o.rebind(\"ALT + TAB\"").count(), 1);
        assert_eq!(g.matches("o.rebind(\"ALT + SHIFT + TAB\"").count(), 1);
        assert!(g.contains("ymux cycle next"));
        assert!(g.contains("ymux cycle prev"));
    }

    #[test]
    fn super_w_closes_through_ymux() {
        let (c, _) = parse("");
        let g = generate(&c, "/home/u/.local/bin/ymux");
        assert!(g.contains("o.rebind(\"SUPER + W\", \"ymux close window\", \"/home/u/.local/bin/ymux action kill-tile\")"));
    }

    #[test]
    fn resize_mode_uses_step_and_polls_super() {
        let (c, _) = parse("set resize-step 30\n");
        let g = generate(&c, "x");
        assert!(g.contains("hl.define_submap(\"ymux_resize\""));
        assert!(g.contains("x = -30, y = 0, relative = true"));
        assert!(g.contains("x = 0, y = 30, relative = true"));
        assert!(g.contains("hl.is_key_down(\"Super_L\")"));
        assert!(g.contains("repeating = true"));
        assert!(g.contains("o.bind(\"SUPER + LEFT\""));
    }

    #[test]
    fn period_and_slash_keys_are_named() {
        let (c, _) = parse("bind / tree\n");
        let g = generate(&c, "x");
        assert!(g.contains("o.bind(\"slash\", \"ymux tree\""));
        assert!(g.contains("o.bind(\"period\", \"ymux move-workspace\""));
    }

    #[test]
    fn quotes_in_exe_are_escaped() {
        assert!(generate(&Config::default(), "/a\"b").contains("hl.exec_cmd(\"/a\\\"b daemon\")"));
    }

    #[test]
    fn generated_lua_parses() {
        use std::io::Write as _;
        use std::process::{Command, Stdio};
        let Ok(mut child) = Command::new("luac").args(["-p", "-"]).stdin(Stdio::piped()).stderr(Stdio::piped()).spawn() else {
            eprintln!("luac not installed; skipping syntax check");
            return;
        };
        child.stdin.take().unwrap().write_all(lua().as_bytes()).unwrap();
        let out = child.wait_with_output().unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    }

    #[test]
    fn placeholder_rule_sends_it_to_the_stash_without_decoration() {
        let g = lua();
        assert!(g.contains("o.window(\"^ymux-placeholder$\""));
        assert!(g.contains("special:ymux-stash silent"));
        // Hyprland 0.56.2 rejects `no_border` ("unknown field"); border_size = 0 covers it
        assert!(!g.contains("no_border"));
        assert!(g.find("ymux-placeholder").unwrap() < g.find(" daemon\")").unwrap());
    }

    #[test]
    fn no_em_dash() {
        assert!(!lua().contains('\u{2014}'));
    }
}
